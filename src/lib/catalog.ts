// Scanners report some codes as 13-digit EAN with a leading 0; the library
// is keyed by the 12-digit UPC form.
export function normalizeBarcode(raw: string): string {
  let d = raw.replace(/\D/g, "");
  while (d.length > 12 && d.startsWith("0")) d = d.slice(1);
  return d;
}

export function catalogLookup(raw: string): CatalogEntry | undefined {
  return UPC_CATALOG[normalizeBarcode(raw)];
}
